#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG_DIR="$ROOT/server"
DATA_DIR="$ROOT/data"
BACKUP_DIR="$ROOT/backups"
SECRETS_FILE="$CONFIG_DIR/secrets.env"
SERVER_CONFIG_FILE="$CONFIG_DIR/config.yaml"
AI_CONFIG_FILE="$CONFIG_DIR/ai.yaml"
SERVICE_NAME="ai-log-monitor-server.service"
SERVICE_FILE="/etc/systemd/system/$SERVICE_NAME"

PUBLIC_URL="http://10.1.0.10:8888"
ADMIN_USER="admin"
ADMIN_PASSWORD=""
ADMIN_TOKEN=""
ENROLL_TOKEN=""
LINE_WEBHOOK_URL=""
GOOGLE_CHAT_WEBHOOK_URL=""
NO_START=0
USE_SYSTEMD=1
DRY_RUN=0
SUDO=""
if [[ "$(id -u)" -ne 0 ]]; then
  SUDO="sudo"
fi

usage() {
  cat <<'EOF'
Usage: ./install-server.sh --public-url URL --admin-user USER --admin-password PASSWORD --enroll-token TOKEN [options]

Options:
  --public-url URL                 LAN URL users and agents can reach.
  --admin-user USER                Dashboard admin username.
  --admin-password PASSWORD        Dashboard admin password.
  --admin-token TOKEN              Optional admin API/session token.
  --enroll-token TOKEN             Token used by new agents during first registration.
  --line-webhook-url URL           Optional LINE notification webhook.
  --google-chat-webhook-url URL    Optional Google Chat notification webhook.
  --no-start                       Write files but do not start the server.
  --no-systemd                     Do not install or enable a systemd service.
  --dry-run                        Print planned changes without writing files.
  -h, --help                       Show this help.
EOF
}

random_token() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 24
    return 0
  fi
  tr -dc 'A-Za-z0-9' </dev/urandom | head -c 48
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --public-url) PUBLIC_URL="${2:?missing value for --public-url}"; shift 2 ;;
    --admin-user) ADMIN_USER="${2:?missing value for --admin-user}"; shift 2 ;;
    --admin-password) ADMIN_PASSWORD="${2:?missing value for --admin-password}"; shift 2 ;;
    --admin-token) ADMIN_TOKEN="${2:?missing value for --admin-token}"; shift 2 ;;
    --enroll-token) ENROLL_TOKEN="${2:?missing value for --enroll-token}"; shift 2 ;;
    --line-webhook-url) LINE_WEBHOOK_URL="${2:?missing value for --line-webhook-url}"; shift 2 ;;
    --google-chat-webhook-url) GOOGLE_CHAT_WEBHOOK_URL="${2:?missing value for --google-chat-webhook-url}"; shift 2 ;;
    --no-start) NO_START=1; shift ;;
    --no-systemd) USE_SYSTEMD=0; shift ;;
    --dry-run) DRY_RUN=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage; exit 1 ;;
  esac
done

if [[ -z "$ADMIN_PASSWORD" && "$DRY_RUN" -eq 0 ]]; then
  ADMIN_PASSWORD="$(random_token)"
fi
if [[ -z "$ADMIN_TOKEN" ]]; then
  ADMIN_TOKEN="$(random_token)"
fi
if [[ -z "$ENROLL_TOKEN" ]]; then
  ENROLL_TOKEN="$(random_token)"
fi

write_secrets() {
  cat >"$SECRETS_FILE" <<EOF
# AI Log Monitor - Server Secrets
# Generated by install-server.sh.
ADMIN_USER=$ADMIN_USER
ADMIN_PASSWORD=$ADMIN_PASSWORD
ADMIN_TOKEN=$ADMIN_TOKEN
ENROLL_TOKEN=$ENROLL_TOKEN
ENFORCE_AGENT_TOKEN=true
RETENTION_DAYS=30
LINE_WEBHOOK_URL=$LINE_WEBHOOK_URL
GOOGLE_CHAT_WEBHOOK_URL=$GOOGLE_CHAT_WEBHOOK_URL
AI_API_ENDPOINT=
AI_API_MODEL=
AI_API_KEY=
EOF
  chmod 600 "$SECRETS_FILE"
}

write_server_config() {
  cat >"$SERVER_CONFIG_FILE" <<EOF
# AI Log Monitor - Server Config
server:
  public_url: "$PUBLIC_URL"
  bind: "0.0.0.0"
  port: 8888

dashboard:
  title: "AI Log Monitor"
  timezone: "Asia/Bangkok"

agents:
  auto_register: true
  auto_active: true
  heartbeat_timeout_seconds: 90

storage:
  data_dir: "/data"
  retention_days: 30
EOF
}

write_ai_config() {
  cat >"$AI_CONFIG_FILE" <<'EOF'
# AI Log Monitor - AI Config
ai:
  enabled: true
  mode: "mock"
  provider: "none"
  model: "none"

providers:
  ollama:
    url: "http://127.0.0.1:11434/api/generate"
    model: "llama3.2:3b"
  api:
    endpoint: "${AI_API_ENDPOINT}"
    api_key: "${AI_API_KEY}"
    model: "${AI_API_MODEL}"

analysis:
  auto_analyze: true
  auto_analyze_min_severity: "critical"
  isolate_by_website: true
  time_window_minutes: 30
  max_context_events: 100
  group_similar_events: true

notifications:
  enabled: true
  language: "th"
  line_webhook_url: "${LINE_WEBHOOK_URL}"
  google_chat_webhook_url: "${GOOGLE_CHAT_WEBHOOK_URL}"

learning:
  enabled: true
  remember_patterns: true
  require_human_confirmation: false
  similarity_threshold: 0.82

limits:
  timeout_seconds: 45
  max_output_tokens: 1200
  daily_ai_calls: 200
EOF
}

systemd_available() {
  command -v systemctl >/dev/null 2>&1 && systemctl list-units >/dev/null 2>&1
}

write_systemd_service() {
  if [[ "$USE_SYSTEMD" -eq 0 ]]; then
    return 0
  fi
  if ! systemd_available; then
    echo "systemd not found; skipping service install"
    return 1
  fi

  $SUDO tee "$SERVICE_FILE" >/dev/null <<EOF
[Unit]
Description=AI Log Monitor Server
Wants=network-online.target
After=network-online.target

[Service]
Type=oneshot
WorkingDirectory=$ROOT
ExecStart=$ROOT/manage.sh start
ExecStop=$ROOT/manage.sh stop
RemainAfterExit=yes
TimeoutStartSec=180

[Install]
WantedBy=multi-user.target
EOF
  $SUDO systemctl daemon-reload
  $SUDO systemctl enable ai-log-monitor-server.service
  return 0
}

start_or_enable_server() {
  if [[ "$USE_SYSTEMD" -eq 1 ]] && systemd_available; then
    write_systemd_service
    if [[ "$NO_START" -eq 1 ]]; then
      echo "Install files written. Start later with: sudo systemctl start $SERVICE_NAME"
      return 0
    fi
    $SUDO systemctl restart "$SERVICE_NAME"
    return 0
  fi

  if [[ "$NO_START" -eq 1 ]]; then
    echo "Install files written. Start later with ./manage.sh start"
    return 0
  fi
  (cd "$ROOT" && ./manage.sh start)
}

print_plan() {
  echo "AI Log Monitor server install plan"
  echo "public url: $PUBLIC_URL"
  echo "admin user: $ADMIN_USER"
  echo "admin password: configured"
  echo "enroll token: configured"
  if [[ -n "$LINE_WEBHOOK_URL" ]]; then
    echo "line webhook: configured"
  else
    echo "line webhook: not configured"
  fi
  if [[ -n "$GOOGLE_CHAT_WEBHOOK_URL" ]]; then
    echo "google chat webhook: configured"
  else
    echo "google chat webhook: not configured"
  fi
  if [[ "$USE_SYSTEMD" -eq 1 ]]; then
    echo "systemd: enabled"
  else
    echo "systemd: disabled"
  fi
}

if [[ "$DRY_RUN" -eq 1 ]]; then
  echo "DRY RUN"
  print_plan
  exit 0
fi

mkdir -p "$CONFIG_DIR" "$DATA_DIR" "$BACKUP_DIR"
write_secrets
write_server_config
write_ai_config
chmod +x "$ROOT/manage.sh"

print_plan
start_or_enable_server
